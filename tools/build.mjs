/* Front matter: the block between the first two "---" lines, one "key: value"
   per line. Values may be quoted; lists are [a, b, c] or "- item" lines. */
function parseFrontMatter(src, file) {
  const m = src.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) throw new Error(`${file}: missing front matter (a block between two "---" lines at the top)`);
  const data = {};
  let listKey = null;
  for (const raw of m[1].split("\n")) {
    if (!raw.trim() || raw.trim().startsWith("#")) continue;
    const item = raw.match(/^\s+-\s+(.*)$/);
    if (item && listKey) { data[listKey].push(unquote(item[1])); continue; }
    const kv = raw.match(/^([A-Za-z_][\w-]*)\s*:\s*(.*)$/);
    if (!kv) throw new Error(`${file}: can't read front-matter line "${raw}"`);
    const [, key, val] = kv;
    listKey = null;
    if (val === "") { data[key] = []; listKey = key; }
    else if (/^\[.*\]$/.test(val)) data[key] = val.slice(1, -1).split(",").map((v) => unquote(v.trim())).filter(Boolean);
    else if (val === "true" || val === "false") data[key] = val === "true";
    else data[key] = unquote(val);
  }
  return { data, body: src.slice(m[0].length) };
}
function unquote(v) {
  v = v.trim();
  if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) {
    return v.slice(1, -1).replace(v[0] === '"' ? /\\(["\\])/g : /''/g, v[0] === '"' ? "$1" : "'");
  }
  return v;
}

function loadPosts() {
  if (!exists(POSTS_DIR)) return [];
  const posts = [];
  const seen = new Map();
  for (const name of fs.readdirSync(path.join(ROOT, POSTS_DIR)).sort()) {
    if (!name.endsWith(".md") || name.toLowerCase() === "readme.md") continue;
    const file = `${POSTS_DIR}/${name}`;
    const { data, body } = parseFrontMatter(read(file), file);
    if (data.draft === true) { warn(`${file}: draft, not published`); continue; }
    for (const k of ["title", "description", "date"]) if (!data[k]) throw new Error(`${file}: front matter needs "${k}"`);
    for (const k of ["date", "updated"]) {
      if (data[k] && !/^\d{4}-\d{2}-\d{2}$/.test(data[k])) throw new Error(`${file}: ${k} must look like 2026-11-16`);
    }
    if (data.updated && data.updated < data.date) throw new Error(`${file}: updated is before date`);
    const slug = data.slug ? slugify(data.slug) : slugify(name.replace(/\.md$/, "").replace(/^\d{4}-\d{2}-\d{2}-/, ""));
    if (!slug) throw new Error(`${file}: can't make a URL slug from the file name`);
    if (seen.has(slug)) throw new Error(`${file}: same URL (blog/${slug}/) as ${seen.get(slug)}`);
    seen.set(slug, file);
    if (data.title.length > 70) warn(`${file}: title is ${data.title.length} characters; search results show about 60`);
    if (data.description.length > 170 || data.description.length < 50) warn(`${file}: description is ${data.description.length} characters; 50 to 160 reads best in search results`);
    const tags = Array.isArray(data.tags) ? data.tags : data.tags ? [data.tags] : [];
    const words = body.replace(/```[\s\S]*?```/g, " ").split(/\s+/).filter((w) => /[A-Za-z0-9]/.test(w)).length;
    posts.push({
      file, slug, body, tags, words,
      title: data.title, description: data.description,
      date: data.date, updated: data.updated || data.date,
      image: data.image || "", imageAlt: data.image_alt || "",
      url: `${SITE}/${BLOG_DIR}/${slug}/`,
      minutes: Math.max(1, Math.round(words / 220))
    });
  }
  // newest first; same day: alphabetical, so the order never depends on the file system
  return posts.sort((a, b) => (b.date.localeCompare(a.date)) || a.slug.localeCompare(b.slug));
}

