function fillRegions(html, regions, file) {
  for (const [name, content] of Object.entries(regions)) {
    const re = new RegExp(`(<!-- build:${name} -->)[\\s\\S]*?(\\n[ \\t]*<!-- /build:${name} -->)`);
    if (!re.test(html)) throw new Error(`${file}: missing <!-- build:${name} --> … <!-- /build:${name} --> markers`);
    html = html.replace(re, (_, open, close) => `${open}\n${content}${close}`);
  }
  return html;
}

