const fmtShort = (d) => {
  if (!d) return "";
  if (d === "upcoming") return "Upcoming";
  if (d === "present") return "Present";
  const [y, m] = String(d).split("-");
  return m ? `${MONTHS_SHORT[+m - 1]} ${y}` : y;
};
const dateKey = (d) => d === "upcoming" ? 1e6 : d === "present" ? 999999 : !d ? 0 : (() => { const [y, m] = String(d).split("-"); return +y * 12 + (m ? +m : 6); })();
const byDate = (a, b) => (dateKey(b.start) - dateKey(a.start)) || (dateKey(b.end || b.start) - dateKey(a.end || a.start));
const imp = (t) => { const v = +t.importance; return v >= 1 && v <= 5 ? Math.round(v) : 3; };

