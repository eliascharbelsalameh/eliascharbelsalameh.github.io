/* "YYYY-MM-DD" -> "YYYY-MM-DDT00:00:00+01:00": midnight in Paris with that
   day's offset (+01:00 in winter, +02:00 in summer). Google's ProfilePage
   rejects a bare date for dateModified. Derived from the date alone (not the
   build time or git), so rebuilding gives the same output and --check holds. */
function parisDateTime(date) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date || "")) return undefined;
  const tz = new Intl.DateTimeFormat("en", { timeZone: "Europe/Paris", timeZoneName: "longOffset" })
    .formatToParts(new Date(`${date}T00:00:00Z`)).find((p) => p.type === "timeZoneName").value;
  return `${date}T00:00:00${tz.replace("GMT", "") || "+00:00"}`;
}

/* The full Person, built from data.js only:
   - jobTitle / description: profile.role, profile.tagline + summary
   - worksFor: ongoing (end: "present") experience entries of importance 5
   - alumniOf: education entries in the "academic" category
   - knowsAbout: the items of the rated skill groups (the ones on the player card) */
function personFull(D, P) {
  const loc = (P.location || "").split(",").map((s) => s.trim()).filter(Boolean);
  const orgs = (pred) => [...new Set(D.timeline.filter(pred).map((t) => t.org).filter(Boolean))];
  const worksFor = orgs((t) => t.kind === "experience" && t.end === "present" && (+t.importance || 3) >= 5);
  const alumniOf = orgs((t) => t.kind === "education" && (t.categories || []).includes("academic"));
  const knowsAbout = D.skills.filter((g) => typeof g.rating === "number").flatMap((g) => g.items || []);
  const person = {
    "@type": "Person", "@id": PERSON_ID,
    name: P.displayName, url: `${SITE}/`,
    image: P.photo ? `${SITE}/${P.photo}` : undefined,
    jobTitle: P.role,
    description: [P.tagline, P.summary].filter(Boolean).join(" "),
    email: P.email ? `mailto:${P.email}` : undefined,
    telephone: P.phone || undefined,
    address: loc.length ? { "@type": "PostalAddress", addressLocality: loc[0], addressCountry: loc[1] } : undefined,
    worksFor: worksFor.length ? worksFor.map((n) => ({ "@type": "Organization", name: n })) : undefined,
    alumniOf: alumniOf.length ? alumniOf.map((n) => ({ "@type": "EducationalOrganization", name: n })) : undefined,
    knowsAbout: knowsAbout.length ? knowsAbout : undefined,
    sameAs: [P.linkedin, P.github].filter(Boolean)
  };
  return JSON.parse(JSON.stringify(person));   // drops the undefined keys
}

