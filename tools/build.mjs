/* =============================================================================
   Site builder: zero dependencies, Node 18 or newer.

     node tools/build.mjs           build everything (run after any edit)
     node tools/build.mjs --check   change nothing; exit 1 if a generated file
                                    is out of date (what the GitHub check runs)

   What it does:
   1. Blog: every posts/*.md (Markdown with front matter) becomes a static page
      at blog/<slug>/index.html, plus the listing blog/index.html and the Atom
      feed blog/feed.xml. Pages of posts that no longer exist are removed.
   2. Home page: rewrites the regions of index.html between
      <!-- build:NAME --> and <!-- /build:NAME --> from assets/js/data.js, so
      the name, role, summary, key figures, every timeline entry, the skills,
      the contact links and the structured data (JSON-LD) are in the HTML for
      search engines, link previews and visitors without JavaScript.
      app.js replaces those regions with the interactive version as usual.
   3. sitemap.xml: home, blog and every post, each with its <lastmod>.

   Output is deterministic (no build timestamps): running it twice in a row
   changes nothing the second time.
   ============================================================================= */
