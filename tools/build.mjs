function feed(posts, P) {
  const updated = posts.reduce((m, p) => (p.updated > m ? p.updated : m), P.updated || "1970-01-01");
  const x = (s) => esc(s).replace(/&#39;/g, "&apos;");
  const entries = posts.map((p) => `  <entry>
    <title>${x(p.title)}</title>
    <link rel="alternate" type="text/html" href="${p.url}"/>
    <id>${p.url}</id>
    <published>${p.date}T00:00:00Z</published>
    <updated>${p.updated}T00:00:00Z</updated>
    <summary>${x(p.description)}</summary>
${p.tags.map((t) => `    <category term="${x(t)}"/>\n`).join("")}    <content type="html">${x(p.feedHtml)}</content>
  </entry>`).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom" xml:lang="en">
  <title>${x(P.displayName)} · ${BLOG_TITLE}</title>
  <subtitle>${x(BLOG_DESCRIPTION)}</subtitle>
  <link rel="self" type="application/atom+xml" href="${SITE}/${BLOG_DIR}/feed.xml"/>
  <link rel="alternate" type="text/html" href="${SITE}/${BLOG_DIR}/"/>
  <id>${SITE}/${BLOG_DIR}/</id>
  <updated>${updated}T00:00:00Z</updated>
  <author>
    <name>${x(P.name)}</name>
    <uri>${SITE}/</uri>
  </author>
${entries}
</feed>
`;
}

function sitemap(posts, P) {
  const latest = posts.reduce((m, p) => (p.updated > m ? p.updated : m), "");
  const url = (loc, lastmod) => `  <url>\n    <loc>${loc}</loc>${lastmod ? `\n    <lastmod>${lastmod}</lastmod>` : ""}\n  </url>`;
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- ${GENERATED}: run "node tools/build.mjs" to update. The home page's
     lastmod is profile.updated in assets/js/data.js; each post's is its
     "updated" (or "date") front matter. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${[url(`${SITE}/`, P.updated), url(`${SITE}/${BLOG_DIR}/`, latest || P.updated), ...posts.map((p) => url(p.url, p.updated))].join("\n")}
</urlset>
`;
}

// copyright year: the newest of profile.updated and the posts' dates, so the
// output never depends on the day the build runs
function yearOf(D, posts) {
  return [D.profile.updated || "", ...posts.map((p) => p.updated)].sort().pop().slice(0, 4) || "2026";
}

