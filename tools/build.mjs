/* A deliberately small Markdown dialect, enough for a technical blog:
   # headings, paragraphs, **bold**, *italic*, ~~strike~~, `code`, fenced code
   blocks (```lang), > quotes, - / 1. lists (nested by indenting), [links](url),
   ![images](url "caption"), <https://autolinks>, --- rules, and hard breaks
   (two trailing spaces or a trailing backslash). Raw HTML is NOT passed
   through: it is shown as text, so a post can never inject markup.

   URLs: http(s), mailto and tel links are kept as they are; any other scheme
   (javascript:, data:, ...) is dropped. Relative paths are read from the site
   root, like the image paths in data.js ("assets/images/blog/x.png",
   "blog/other-post/"), and fixed up for the page's folder. */

const BLOCK_START = /^ {0,3}(?:#{1,6}(?:\s|$)|>|```|~~~|[-*+]\s|\d{1,9}[.)]\s|([-*_])(?: *\1){2,} *$)/;

function makeUrl(raw, ctx) {
  const u = raw.trim().replace(/^<|>$/g, "");
  if (/^(?:https?:|mailto:|tel:)/i.test(u)) return u;
  if (/^[a-z][a-z0-9+.-]*:/i.test(u)) { warn(`${ctx.file}: dropped unsafe link "${u}"`); return "#"; }
  if (u.startsWith("//")) return u;   // protocol-relative: external
  if (u.startsWith("#") || u.startsWith("./") || u.startsWith("../")) return u;
  return ctx.root + u.replace(/^\//, "");   // "assets/x.png", "/assets/x.png", "/" (home): from the site root
}

/* [text](url "title") starting at src[i] === "[" -> { text, url, title, end } */
function parseLink(src, i) {
  let depth = 0, j = i;
  for (; j < src.length; j++) {
    const c = src[j];
    if (c === "\\") { j++; continue; }
    if (c === "`") { const k = src.indexOf("`", j + 1); if (k > 0) { j = k; continue; } }
    if (c === "[") depth++;
    else if (c === "]" && --depth === 0) break;
  }
  if (j >= src.length || src[j + 1] !== "(") return null;
  const text = src.slice(i + 1, j);
  let k = j + 2;
  while (src[k] === " ") k++;
  let url = "";
  if (src[k] === "<") {
    const e = src.indexOf(">", k);
    if (e < 0) return null;
    url = src.slice(k + 1, e); k = e + 1;
  } else {
    let par = 0;
    for (; k < src.length; k++) {
      const c = src[k];
      if (c === "\\" && k + 1 < src.length) { url += src[++k]; continue; }
      if (/\s/.test(c)) break;
      if (c === "(") par++;
      if (c === ")") { if (par === 0) break; par--; }
      url += c;
    }
  }
  while (src[k] === " " || src[k] === "\n") k++;
  let title = "";
  const q = src[k];
  if (q === '"' || q === "'" || q === "(") {
    const close = q === "(" ? ")" : q;
    const e = src.indexOf(close, k + 1);
    if (e < 0) return null;
    title = src.slice(k + 1, e); k = e + 1;
    while (src[k] === " ") k++;
  }
  if (src[k] !== ")") return null;
  return { text, url, title, end: k + 1 };
}

function imgTag(alt, rawUrl, title, ctx) {
  const src = makeUrl(rawUrl, ctx);
  const local = rawUrl.trim();
  if (src === "#") return "";   // unsafe scheme: makeUrl already warned
  const size = !/^[a-z][a-z0-9+.-]*:/i.test(local) ? imageSize(local.replace(/^\.?\//, "")) : null;
  if (!size && !/^[a-z]+:/i.test(local)) warn(`${ctx.file}: image "${local}" not found (or unknown size); check the path`);
  if (!alt) warn(`${ctx.file}: image "${local}" has no alt text`);
  return `<img src="${esc(src)}" alt="${esc(alt)}"${title ? ` title="${esc(title)}"` : ""}` +
    (size ? ` width="${size.w}" height="${size.h}"` : "") + ` loading="lazy" decoding="async">`;
}

function inline(src, ctx) {
  const slots = [];
  const put = (html) => "\u0000" + (slots.push(html) - 1) + "\u0000";
  let s = "";
  src = src.replace(/(?: {2,}|\\)\n/g, "\u0001");   // hard line breaks
  for (let i = 0; i < src.length;) {
    const c = src[i];
    if (c === "\\" && /[!-/:-@[-`{-~]/.test(src[i + 1] || "")) { s += put(esc(src[i + 1])); i += 2; continue; }
    if (c === "`") {
      let j = i; while (src[j] === "`") j++;
      const run = src.slice(i, j);
      let k = j, close = -1;
      while ((k = src.indexOf(run, k)) !== -1) {
        if (src[k + run.length] !== "`" && src[k - 1] !== "`") { close = k; break; }
        while (src[k] === "`") k++;
      }
      if (close === -1) { s += run; i = j; continue; }
      let code = src.slice(j, close).replace(/\u0001/g, " \n").replace(/\n/g, " ");
      if (/^ .*[^ ].* $/.test(code)) code = code.slice(1, -1);
      s += put(`<code>${esc(code)}</code>`);
      i = close + run.length; continue;
    }
    if (c === "!" && src[i + 1] === "[") {
      const r = parseLink(src, i + 1);
      if (r) { s += put(imgTag(r.text.replace(/\\(.)/g, "$1"), r.url, r.title, ctx)); i = r.end; continue; }
    }
    if (c === "[" && !ctx.inLink) {
      const r = parseLink(src, i);
      if (r) {
        const inner = inline(r.text, { ...ctx, inLink: true });
        s += put(`<a href="${esc(makeUrl(r.url, ctx))}"${r.title ? ` title="${esc(r.title)}"` : ""}>${inner}</a>`);
        i = r.end; continue;
      }
    }
    if (c === "<") {
      const m = src.slice(i).match(/^<((?:https?:\/\/|mailto:)[^\s<>]+)>/i);
      if (m && !ctx.inLink) { const label = m[1].replace(/^mailto:/i, ""); s += put(`<a href="${esc(m[1])}">${esc(label)}</a>`); i += m[0].length; continue; }
    }
    s += c; i++;
  }
  let h = esc(s)
    .replace(/\*\*\*(?=\S)([\s\S]*?\S)\*\*\*/g, "<strong><em>$1</em></strong>")
    .replace(/\*\*(?=\S)([\s\S]*?\S)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[^\w\u0000])__(?=\S)([\s\S]*?\S)__(?![\w])/g, "$1<strong>$2</strong>")
    .replace(/\*(?=\S)([\s\S]*?\S)\*/g, "<em>$1</em>")
    .replace(/(^|[^\w\u0000])_(?=\S)([\s\S]*?\S)_(?![\w])/g, "$1<em>$2</em>")
    .replace(/~~(?=\S)([\s\S]*?\S)~~/g, "<del>$1</del>")
    .replace(/\u0001/g, "<br>\n");
  for (let n = 0; n < 3 && h.includes("\u0000"); n++) h = h.replace(/\u0000(\d+)\u0000/g, (_, k) => slots[+k]);
  return h;
}

function blocks(lines, ctx, tight = false) {
  const out = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    let m;

    // fenced code block
    if ((m = line.match(/^( {0,3})(`{3,}|~{3,})\s*([^\s`]*)/))) {
      const indent = m[1].length, fence = m[2], lang = m[3];
      const closeRe = new RegExp("^ {0,3}" + (fence[0] === "`" ? "`" : "~") + "{" + fence.length + ",}\\s*$");
      const body = [];
      i++;
      while (i < lines.length && !closeRe.test(lines[i])) { body.push(lines[i].replace(new RegExp("^ {0," + indent + "}"), "")); i++; }
      i++;
      const cls = lang ? ` class="language-${esc(lang.toLowerCase())}"` : "";
      out.push(`<pre><code${cls}>${esc(body.join("\n"))}</code></pre>`);
      continue;
    }

    // ATX heading; the page title is the only h1, so # becomes h2 (see ctx.shift)
    if ((m = line.match(/^ {0,3}(#{1,6})(?:\s+(.*?))?(?:\s+#+)?\s*$/))) {
      const level = Math.min(6, m[1].length + ctx.shift);
      const text = m[2] || "";
      let id = slugify(text.replace(/\]\([^)]*\)/g, "").replace(/[`*_~[\]\\]/g, "")) || "section";
      if (ctx.ids.has(id)) { let n = 2; while (ctx.ids.has(id + "-" + n)) n++; id += "-" + n; }
      ctx.ids.add(id);
      out.push(`<h${level} id="${id}">${inline(text, ctx)}</h${level}>`);
      i++; continue;
    }

    // thematic break
    if (/^ {0,3}([-*_])(?: *\1){2,} *$/.test(line)) { out.push("<hr>"); i++; continue; }

    // block quote
    if (/^ {0,3}>/.test(line)) {
      const body = [];
      while (i < lines.length && lines[i].trim() && (/^ {0,3}>/.test(lines[i]) || !BLOCK_START.test(lines[i]))) {
        body.push(lines[i].replace(/^ {0,3}> ?/, "")); i++;
        if (i < lines.length && !lines[i].trim() && /^ {0,3}>/.test(lines[i + 1] || "")) { body.push(""); i++; }
      }
      out.push(`<blockquote>\n${blocks(body, ctx)}\n</blockquote>`);
      continue;
    }

    // list (- * + or 1. 1)), nested by indentation
    if ((m = line.match(/^( {0,3})([-*+]|\d{1,9}[.)])(\s+|$)/))) {
      const ordered = /\d/.test(m[2]);
      const start = ordered ? parseInt(m[2], 10) : 1;
      // the same marker style continues the list ("-" vs "*", "1." vs "1)"); another starts a new one
      const markerRe = ordered
        ? new RegExp("^( *)(\\d{1,9}\\" + m[2].slice(-1) + ")(\\s+|$)(.*)$")
        : new RegExp("^( *)(\\" + m[2] + ")(\\s+|$)(.*)$");
      const base = m[1].length;
      const items = [];
      let loose = false, item = null;
      while (i < lines.length) {
        const l = lines[i];
        const lm = l.match(markerRe);
        if (lm && lm[1].length <= base + 1 && !/^ {0,3}([-*_])(?: *\1){2,} *$/.test(l)) {
          item = { offset: lm[1].length + lm[2].length + Math.min(lm[3].length || 1, 4), lines: [lm[4]] };
          items.push(item); i++; continue;
        }
        if (!l.trim()) {
          let j = i + 1;
          while (j < lines.length && !lines[j].trim()) j++;
          if (j >= lines.length) break;
          const next = lines[j], ind = next.match(/^ */)[0].length;
          if (ind >= item.offset || (markerRe.test(next) && ind <= base + 1)) {
            loose = true;   // blank line between items, or between blocks inside one
            for (let k = i; k < j; k++) item.lines.push("");
            i = j; continue;
          }
          break;
        }
        const ind = l.match(/^ */)[0].length;
        if (ind >= item.offset) { item.lines.push(l.slice(item.offset)); i++; continue; }
        if (ind > base && /^\s*([-*+]|\d{1,9}[.)])\s/.test(l)) { item.lines.push(l.slice(Math.min(ind, item.offset))); i++; continue; }
        if (!BLOCK_START.test(l) && item.lines[item.lines.length - 1].trim()) { item.lines.push(l.trim()); i++; continue; }
        break;
      }
      // a blank line between items (not just inside one) makes the list "loose": <p> in every item
      const lis = items.map((it) => {
        while (it.lines.length && !it.lines[it.lines.length - 1].trim()) it.lines.pop();
        return `<li>${blocks(it.lines, ctx, !loose)}</li>`;
      });
      const tag = ordered ? "ol" : "ul";
      out.push(`<${tag}${ordered && start !== 1 ? ` start="${start}"` : ""}>\n${lis.join("\n")}\n</${tag}>`);
      continue;
    }

    // paragraph
    const para = [line.trim()];
    i++;
    while (i < lines.length && lines[i].trim() && !BLOCK_START.test(lines[i])) { para.push(lines[i].replace(/^\s+/, "")); i++; }
    const text = para.join("\n");
    const html = inline(text, ctx);
    // a paragraph that is only an image with a title becomes a captioned figure
    const fig = text.match(/^!\[[^\]]*\]\([^)]*?\s+(["'])(.+)\1\s*\)$/);
    if (fig && !tight) out.push(`<figure>\n${html.replace(/ title="[^"]*"/, "")}\n<figcaption>${inline(fig[2], ctx)}</figcaption>\n</figure>`);
    else out.push(tight ? html : `<p>${html}</p>`);
  }
  return out.join("\n");
}

function renderMarkdown(src, ctx) {
  const lines = src.replace(/\t/g, "    ").split("\n");
  // the page title is the h1: if the post uses "#" headings, push every level down one
  const usesH1 = lines.some((l) => /^ {0,3}#(?:\s|$)/.test(l));
  if (usesH1) warn(`${ctx.file}: "#" headings were turned into "##" (the post title is the page's only h1)`);
  return blocks(lines, { ...ctx, shift: usesH1 ? 1 : 0, ids: new Set() });
}

